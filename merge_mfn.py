def build():
    out = {}
    for name, spec in MFN_RUNS.items():
        entry = {'params': spec['params'], 'seeds': [0, 1, 2, 3, 4]}
        for k in (5, 10, 20):
            vals = [r[k] for r in spec['runs']]
            mean = statistics.mean(vals)
            var = statistics.pvariance(vals)
            entry[f'k{k}'] = {'mean': mean, 'std': var ** 0.5, 'runs': vals}
        out[name] = entry
    return out


def main():
    with open('results.json') as f:
        current = json.load(f)
    mfn = build()
    merged = {**mfn, **current}
    with open('results.json', 'w') as f:
        json.dump(merged, f, indent=2)
    for name in merged:
        print(name, merged[name].get('params'), 'seeds:',
              len(merged[name].get('k5', {}).get('runs', [])))


if __name__ == '__main__':
    main()